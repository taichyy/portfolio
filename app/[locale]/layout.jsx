import { notFound } from "next/navigation"
import { Analytics } from "@vercel/analytics/next"
import localFont from "next/font/local"
import { Bricolage_Grotesque, JetBrains_Mono } from "next/font/google"

import "../globals.css"
import SiteNav from "@/components/site-nav"
import { EMAIL, GITHUB_URL } from "@/lib/site"
import { getEducation } from "@/lib/profile"
import { getDictionary } from "@/lib/i18n/dictionaries"
import SmoothNavigate from "@/components/smooth-navigate"
import { SITE_URL, localeAlternates } from "@/lib/i18n/seo"
import I18nProvider from "@/components/providers/i18n-provider"
import { LOCALES, LOCALE_META, isLocale } from "@/lib/i18n/config"
import { ThemeProvider } from "@/components/providers/theme-provider"

const latin = Bricolage_Grotesque({
    subsets: ["latin"],
    axes: ["opsz", "wdth"],
    variable: "--font-latin",
    display: "swap",
})

// Chinese display headings only; body Chinese uses system fonts. The subset is
// generated by scripts/subset-display-font.mjs on prebuild.
const cjk = localFont({
    src: "../fonts/noto-sans-tc-800-subset.woff2",
    weight: "800",
    variable: "--font-cjk-display",
    display: "swap",
    preload: false,
    declarations: [
        {
            prop: "unicode-range",
            value: "U+2E80-2FDF, U+3000-303F, U+3400-4DBF, U+4E00-9FFF, U+F900-FAFF, U+FE30-FE4F, U+FF00-FFEF",
        },
    ],
})

const mono = JetBrains_Mono({
    subsets: ["latin"],
    variable: "--font-mono",
    display: "swap",
})

// Tenure and "present" periods depend on today's date.
export const revalidate = 86400

export function generateStaticParams() {
    return LOCALES.map((locale) => ({ locale }))
}

export async function generateMetadata(props) {
    const { locale } = await props.params

    if (!isLocale(locale)) return {}

    const dict = getDictionary(locale)

    return {
        metadataBase: new URL(SITE_URL),
        title: {
            default: dict.meta.title,
            template: dict.meta.titleTemplate,
        },
        description: dict.meta.description,
        keywords: dict.meta.keywords,
        authors: [{ name: "Tai", url: SITE_URL }],
        creator: "Tai",
        alternates: localeAlternates(locale),
        openGraph: {
            type: "website",
            locale: LOCALE_META[locale].ogLocale,
            url: `${SITE_URL}/${locale}`,
            siteName: "Tai",
            title: dict.meta.title,
            description: dict.meta.shortDescription,
        },
        twitter: {
            card: "summary_large_image",
            title: dict.meta.title,
            description: dict.meta.twitterDescription,
        },
        robots: {
            index: true,
            follow: true,
            googleBot: {
                index: true,
                follow: true,
                "max-image-preview": "large",
                "max-snippet": -1,
            },
        },
    }
}

export const viewport = {
    themeColor: [
        { media: "(prefers-color-scheme: light)", color: "#ffffff" },
        { media: "(prefers-color-scheme: dark)", color: "#171717" },
    ],
}

const personJsonLd = (locale, dict, school) => ({
    "@context": "https://schema.org",
    "@type": "Person",
    name: "Tai",
    url: `${SITE_URL}/${locale}`,
    email: `mailto:${EMAIL}`,
    image: `${SITE_URL}/images/contact/logo-whitebg.png`,
    jobTitle: dict.meta.jobTitle,
    alumniOf: {
        "@type": "CollegeOrUniversity",
        name: school,
    },
    knowsAbout: [
        "Next.js",
        "React",
        "TypeScript",
        "Node.js",
        "MongoDB",
        "Web Development",
        "Product Building",
        "AI Coding Agents",
        "Automation",
    ],
    sameAs: [GITHUB_URL],
})

const RootLayout = async (props) => {
    const { children } = props;
    const { locale } = await props.params;

    if (!isLocale(locale)) notFound();

    const dict = getDictionary(locale);

    return (
        <html
            lang={LOCALE_META[locale].htmlLang}
            suppressHydrationWarning
            className={`${latin.variable} ${cjk.variable} ${mono.variable}`}
        >
            <body className="font-sans min-h-screen bg-background text-foreground antialiased">
                <script
                    type="application/ld+json"
                    dangerouslySetInnerHTML={{
                        __html: JSON.stringify(
                            personJsonLd(locale, dict, getEducation(locale)[0].school),
                        ),
                    }}
                />
                <I18nProvider locale={locale}>
                    <ThemeProvider
                        attribute="class"
                        defaultTheme="light"
                        enableSystem={false}
                        disableTransitionOnChange={false}
                    >
                        <Analytics />
                        <SmoothNavigate />
                        <SiteNav />
                        {children}
                    </ThemeProvider>
                </I18nProvider>
            </body>
        </html>
    )
}

export default RootLayout
